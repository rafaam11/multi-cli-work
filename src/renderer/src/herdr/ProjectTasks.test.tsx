import {cleanup,fireEvent,render,screen,waitFor} from '@testing-library/react';
import {afterEach,expect,it,vi} from 'vitest';
import type {McwV2Api} from '@shared/v2-api';
import type {WorkProject} from '@shared/work-project-types';
import {ProjectTasks} from './ProjectTasks';
vi.mock('./TaskPanel',()=>({TaskPanel:(props:any)=><div data-testid="task-scope">{props.hostId??'local'}:{props.projectId}</div>}));
afterEach(cleanup);
it('discards a catalog reply after the selected owner changes',async()=>{
  let finish!:(value:unknown)=>void;
  const host={executionHosts:async()=>[{hostId:'remote',name:'Lab PC',connected:true}],executionCatalog:vi.fn(()=>new Promise(resolve=>{finish=resolve;}))} as unknown as McwV2Api;
  const save=vi.fn(async()=>{}),project={id:'local-project'} as WorkProject;
  render(<ProjectTasks project={project} defaultCwd="/local" api={host} onLinksChange={save}/>);
  await screen.findByRole('option',{name:'Lab PC'});fireEvent.change(screen.getByLabelText('대표 실행 PC'),{target:{value:'remote'}});
  await waitFor(()=>expect(host.executionCatalog).toHaveBeenCalledWith('remote'));
  fireEvent.change(screen.getByLabelText('대표 실행 PC'),{target:{value:''}});
  finish({repositories:[{projectId:'stale',projectName:'Stale reply'}]});
  expect(screen.getByTestId('task-scope')).toHaveTextContent('local:local-project');
  expect(screen.queryByLabelText('연결할 원격 프로젝트')).not.toBeInTheDocument();expect(save).not.toHaveBeenCalled();
});
it('only saves a remote association on explicit action and scopes tasks to that remote identity',async()=>{
  const host={executionHosts:vi.fn(async()=>[{hostId:'remote',name:'Lab PC',connected:true}]),executionCatalog:vi.fn(async()=>({hostId:'remote',repositories:[{id:'repo',projectId:'remote-project',projectName:'Remote research'}]}))} as unknown as McwV2Api;
  const project={id:'local-project',hostProjects:[]} as unknown as WorkProject,save=vi.fn(async()=>{});
  const view=render(<ProjectTasks project={project} defaultCwd="/local" api={host} onLinksChange={save}/>);
  expect(screen.getByTestId('task-scope')).toHaveTextContent('local:local-project');
  fireEvent.change(await screen.findByLabelText('대표 실행 PC'),{target:{value:'remote'}});
  await screen.findByRole('option',{name:'Remote research'});
  expect(screen.queryByTestId('task-scope')).not.toBeInTheDocument();expect(save).not.toHaveBeenCalled();
  fireEvent.change(screen.getByLabelText('연결할 원격 프로젝트'),{target:{value:'remote-project'}});
  expect(save).not.toHaveBeenCalled();fireEvent.click(screen.getByRole('button',{name:'프로젝트 연결'}));
  const links=[{hostId:'remote',projectId:'remote-project',projectName:'Remote research'}];
  await waitFor(()=>expect(save).toHaveBeenCalledWith(links));
  view.rerender(<ProjectTasks project={{...project,hostProjects:links}} defaultCwd="/local" api={host} onLinksChange={save}/>);
  expect(screen.getByTestId('task-scope')).toHaveTextContent('remote:remote-project');
  expect(screen.getByTestId('task-scope')).not.toHaveTextContent('local-project');
});
